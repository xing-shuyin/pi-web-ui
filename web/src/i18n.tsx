export type Translate = (key: keyof typeof zh, vars?: Record<string, string | number>) => string;

interface I18nContextValue {
	locale: Locale;
	setLocale: (locale: Locale) => void;
	t: Translate;
}

const I18nContext = createContext<I18nContextValue | null>(null);

function loadLocale(): Locale {
	try {
		const saved = localStorage.getItem(STORAGE_KEY);
		if (saved === "zh" || saved === "en" || saved === "it") return saved;
	} catch {
		// localStorage unavailable — fall through to the default.
	}
	return "zh"; // default: Chinese
}

export function LanguageProvider({ children }: { children: ReactNode }) {
	const [locale, setLocaleState] = useState<Locale>(loadLocale);

	const setLocale = useCallback((l: Locale) => {
		setLocaleState(l);
		try {
			localStorage.setItem(STORAGE_KEY, l);
		} catch {
			// ignore storage errors
		}
	}, []);

	const t = useCallback<Translate>(
		(key, vars) => {
			let str: string = en[key];
			if (locale === "zh") str = zh[key];
			else if (locale === "it") str = it[key];
			if (vars) {
				for (const [k, v] of Object.entries(vars)) {
					str = str.replaceAll(`{${k}}`, String(v));
				}
			}
			return str;
		},
		[locale],
	);

	useEffect(() => {
		document.documentElement.lang = locale === "zh" ? "zh-CN" : locale === "it" ? "it" : "en";
		// 标题由 App 统一维护（项目名优先，见 App.tsx 的 document.title effect）。
	}, [locale]);

	const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);

	return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
	const ctx = useContext(I18nContext);
	if (!ctx) throw new Error("useI18n must be used within LanguageProvider");
	return ctx;
}

/** Convenience: translation function only. */
export function useT(): Translate {
	return useI18n().t;
}
