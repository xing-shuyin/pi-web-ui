package app.pi.mobile.localengine;

import android.content.Context;
import android.content.res.AssetManager;

import org.apache.commons.compress.archivers.tar.TarArchiveEntry;
import org.apache.commons.compress.archivers.tar.TarArchiveInputStream;
import org.apache.commons.compress.compressors.gzip.GzipCompressorInputStream;

import java.io.ByteArrayOutputStream;
import java.io.File;
import java.io.FileInputStream;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.SequenceInputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Locale;

/**
 * Extracts the bundled rootfs (APK assets localengine/) into app-private storage.
 *
 * Layout inside assets:
 *   localengine/runtime.json          — {version, abi, volumes:[{name, bytes, sha256}]}
 *   localengine/<volume>.part-NNN     — slices of one rootfs.tgz
 *
 * Commit is transactional: everything lands in engine/staging, then swaps with engine/rootfs.
 * The user data directory (filesDir/data) is never touched here.
 */
public final class RuntimeInstaller {

	public static final String ASSET_DIR = "localengine";
	public static final String MANIFEST_ASSET = ASSET_DIR + "/runtime.json";
	public static final String MANIFEST_FILE = ".runtime.json";

	/** Parsed form of localengine/runtime.json. */
	public static final class Manifest {
		public final String version;
		public final String abi;
		public final List<Volume> volumes;

		Manifest(String version, String abi, List<Volume> volumes) {
			this.version = version;
			this.abi = abi;
			this.volumes = volumes;
		}
	}

	public static final class Volume {
		public final String name;
		public final long bytes;
		public final String sha256;

		Volume(String name, long bytes, String sha256) {
			this.name = name;
			this.bytes = bytes;
			this.sha256 = sha256;
		}
	}

	public interface ProgressListener {
		void onProgress(String step, long done, long total);
	}

	private RuntimeInstaller() {}

	public static File engineRoot(Context context) {
		return new File(context.getFilesDir(), "engine");
	}

	public static File rootfsDir(Context context) {
		return new File(engineRoot(context), "rootfs");
	}

	public static File dataRoot(Context context) {
		return new File(context.getFilesDir(), "data");
	}

	/** Reads and parses the manifest bundled in the APK. Throws when engine assets are missing. */
	public static Manifest readBuiltinManifest(Context context) throws IOException {
		byte[] raw = readAsset(context, MANIFEST_ASSET);
		return parseManifest(new String(raw, StandardCharsets.UTF_8), "asset");
	}

	/** Parses the stored manifest of an extracted runtime; null when nothing is installed. */
	public static Manifest readInstalledManifest(Context context) throws IOException {
		File stored = new File(engineRoot(context), MANIFEST_FILE);
		if (!stored.isFile()) return null;
		return parseManifest(new String(Files.readAllBytes(stored.toPath()), StandardCharsets.UTF_8), "installed");
	}

	private static Manifest parseManifest(String json, String source) throws IOException {
		// Minimal dependency-free parsing: the manifest is generated by our build script with a
		// stable field order, so tolerant field scans are deterministic here.
		String version = extractString(json, "version");
		String abi = extractString(json, "abi");
		if (version == null || abi == null) {
			throw new IOException("运行环境清单损坏（" + source + "）：缺少 version/abi。");
		}
		List<Volume> volumes = new ArrayList<>();
		int volumesAt = json.indexOf("\"volumes\"");
		if (volumesAt >= 0) {
			int cursor = json.indexOf('{', volumesAt);
			while (cursor >= 0) {
				int end = json.indexOf('}', cursor);
				if (end < 0) break;
				String body = json.substring(cursor, end + 1);
				String name = extractString(body, "name");
				String sha256 = extractString(body, "sha256");
				Long bytes = extractNumber(body, "bytes");
				if (name != null && sha256 != null && bytes != null) volumes.add(new Volume(name, bytes, sha256));
				cursor = json.indexOf('{', end);
			}
		}
		if (volumes.isEmpty()) throw new IOException("运行环境清单损坏（" + source + "）：没有分卷记录。");
		return new Manifest(version, abi, volumes);
	}

	private static String extractString(String json, String field) {
		String needle = "\"" + field + "\"";
		int at = json.indexOf(needle);
		if (at < 0) return null;
		int colon = json.indexOf(':', at + needle.length());
		int open = json.indexOf('"', colon);
		int close = json.indexOf('"', open + 1);
		if (colon < 0 || open < 0 || close < 0) return null;
		return json.substring(open + 1, close);
	}

	private static Long extractNumber(String json, String field) {
		String needle = "\"" + field + "\"";
		int at = json.indexOf(needle);
		if (at < 0) return null;
		int colon = json.indexOf(':', at + needle.length());
		if (colon < 0) return null;
		int end = colon + 1;
		while (end < json.length() && "0123456789".indexOf(json.charAt(end)) < 0 && json.charAt(end) != '-') end++;
		if (end >= json.length()) return null;
		int digits = end;
		while (digits < json.length() && Character.isDigit(json.charAt(digits))) digits++;
		if (digits == end) return null;
		try {
			return Long.parseLong(json.substring(end, digits));
		} catch (NumberFormatException failure) {
			return null;
		}
	}

	/** Extracts the bundled runtime; safe to call again only after reset() or a failed install. */
	public static void install(Context context, ProgressListener progress) throws IOException, InterruptedException {
		Manifest manifest = readBuiltinManifest(context);
		File engineRoot = engineRoot(context);
		File staging = new File(engineRoot, "staging");
		File rootfs = rootfsDir(context);
		if (rootfs.isDirectory() && !deleteRecursively(rootfs)) {
			throw new IOException("旧的运行环境无法清理，请重置后重试。");
		}
		if (staging.exists() && !deleteRecursively(staging)) {
			throw new IOException("上次中断的安装现场无法清理，请重置后重试。");
		}
		if (!staging.mkdirs()) throw new IOException("无法创建安装目录。");

		EngineState.setAbi(manifest.abi);
		EngineState.setBuiltinVersion(manifest.version);
		EngineState.setPhase(EngineState.PHASE_INSTALLING);

		try {
			extractVolumes(context, manifest, staging, progress);
			// Persist the manifest next to the extracted tree, then commit atomically.
			byte[] manifestRaw = readAsset(context, MANIFEST_ASSET);
			Files.write(new File(engineRoot, MANIFEST_FILE).toPath(), manifestRaw);
			File target = rootfs;
			if (!staging.renameTo(target)) {
				// Same-volume rename should not fail, but keep the failure loud instead of silent.
				throw new IOException("安装提交失败：无法把 staging 改名为 rootfs。");
			}
			EngineState.setInstalledVersion(manifest.version);
			restoreKeptData(context, true); // 若有 reset 时挪出的用户数据，挪回新 rootfs
			EngineState.systemLog("运行环境已安装：" + manifest.version + "（" + manifest.abi + "）");
			EngineState.setPhase(EngineState.PHASE_INSTALLED);
		} catch (IOException | RuntimeException failure) {
			EngineState.setError("安装失败：" + failure.getMessage());
			deleteRecursively(staging);
			throw failure;
		}
	}

	private static void extractVolumes(Context context, Manifest manifest, File staging, ProgressListener progress)
		throws IOException, InterruptedException {
		AssetManager assets = context.getAssets();
		List<InputStream> parts = new ArrayList<>();
		long totalBytes = 0;
		try {
			for (Volume volume : manifest.volumes) {
				parts.add(assets.open(ASSET_DIR + "/" + volume.name));
				totalBytes += volume.bytes;
			}
		} catch (IOException failure) {
			closeAll(parts);
			throw new IOException("APK 内缺少运行环境分卷（需要先由 CI 构建产物填充）：" + failure.getMessage());
		}
		long copiedBytes = 0;
		try (InputStream joined = new SequenceInputStream(Collections.enumeration(parts));
			GzipCompressorInputStream gzip = new GzipCompressorInputStream(joined, true);
			TarArchiveInputStream tar = new TarArchiveInputStream(gzip, StandardCharsets.UTF_8.name())) {
			TarArchiveEntry entry;
			while ((entry = tar.getNextEntry()) != null) {
				String entryName = entry.getName();
				if (entryName.contains("..") || entryName.startsWith("/") || entryName.contains("\\")) {
					throw new IOException("运行环境归档含非法路径：" + entryName);
				}
				File target = new File(staging, entryName);
				if (entry.isDirectory()) {
					if (!target.isDirectory() && !target.mkdirs()) throw new IOException("无法创建目录：" + entryName);
					continue;
				}
				File parent = target.getParentFile();
				if (parent != null && !parent.isDirectory() && !parent.mkdirs()) {
					throw new IOException("无法创建目录：" + parent);
				}
				if (entry.isSymbolicLink()) {
					String linkName = entry.getLinkName();
					try {
						Files.deleteIfExists(target.toPath());
						Files.createSymbolicLink(target.toPath(), new File(linkName).toPath());
					} catch (IOException failure) {
						throw new IOException("无法还原符号链接 " + entryName + "：" + failure.getMessage());
					}
					continue;
				}
				MessageDigest digest = MessageDigest.getInstance("SHA-256");
				try (FileOutputStream out = new FileOutputStream(target)) {
					byte[] buffer = new byte[64 * 1024];
					int read;
					while ((read = tar.read(buffer)) >= 0) {
						out.write(buffer, 0, read);
						digest.update(buffer, 0, read);
						copiedBytes += read;
						if (progress != null) progress.onProgress("extract", copiedBytes, -1); // 解压字节大于压缩总体积，total 未知，前端显示 MB
					}
				}
				int mode = entry.getMode() & 07777;
				if ((mode & 0111) != 0 && !target.setExecutable(true, false)) {
					EngineState.systemLog("警告：无法赋予执行权限 " + entryName);
				}
			}
		} catch (java.security.GeneralSecurityException failure) {
			throw new IOException("SHA-256 不可用：" + failure.getMessage());
		}
		// Volume integrity is enforced by streaming each asset against its pinned sha256
		// (verifyVolumes); extraction itself only checks path safety and exec bits.
		verifyVolumes(context, manifest, progress);
		EngineState.systemLog(
			String.format(Locale.US, "解压完成：约 %.1f MB", copiedBytes / 1024.0 / 1024.0)
		);
	}

	/** Streams each volume from assets and checks its pinned sha256 before extraction commit. */
	private static void verifyVolumes(Context context, Manifest manifest, ProgressListener progress)
		throws IOException {
		long index = 0;
		for (Volume volume : manifest.volumes) {
			MessageDigest digest;
			try {
				digest = MessageDigest.getInstance("SHA-256");
			} catch (java.security.GeneralSecurityException failure) {
				throw new IOException("SHA-256 不可用：" + failure.getMessage());
			}
			try (InputStream in = context.getAssets().open(ASSET_DIR + "/" + volume.name)) {
				byte[] buffer = new byte[64 * 1024];
				long seen = 0;
				int read;
				while ((read = in.read(buffer)) >= 0) {
					digest.update(buffer, 0, read);
					seen += read;
					if (progress != null) progress.onProgress("verify", index + seen, totalVolumeBytes(manifest));
				}
				if (seen != volume.bytes) {
					throw new IOException("分卷大小不符：" + volume.name);
				}
			}
			String actual = hex(digest.digest());
			if (!actual.equalsIgnoreCase(volume.sha256)) {
				throw new IOException("分卷校验失败：" + volume.name);
			}
			index += volume.bytes;
		}
	}

	private static long totalVolumeBytes(Manifest manifest) {
		long total = 0;
		for (Volume volume : manifest.volumes) total += volume.bytes;
		return total;
	}

	private static byte[] readAsset(Context context, String path) throws IOException {
		try (InputStream in = context.getAssets().open(path);
			ByteArrayOutputStream out = new ByteArrayOutputStream()) {
			byte[] buffer = new byte[32 * 1024];
			int read;
			while ((read = in.read(buffer)) >= 0) out.write(buffer, 0, read);
			return out.toByteArray();
		}
	}

	private static String hex(byte[] bytes) {
		StringBuilder builder = new StringBuilder(bytes.length * 2);
		for (byte value : bytes) builder.append(String.format(Locale.US, "%02x", value));
		return builder.toString();
	}

	private static void closeAll(List<InputStream> streams) {
		for (InputStream stream : streams) {
			try {
				stream.close();
			} catch (IOException ignored) {
				// nothing meaningful to do while unwinding
			}
		}
	}

	public static boolean deleteRecursively(File root) {
		if (root == null || !root.exists()) return true;
		File[] children = root.listFiles();
		if (children != null) {
			for (File child : children) {
				if (!deleteRecursively(child)) return false;
			}
		}
		return root.delete();
	}

	/** User data survives reset：先把数据目录挪出 rootfs，删完再挪回。 */
	public static void reset(Context context) {
		File dataRoot = new File(rootfsDir(context), "root/piwebui-data");
		File keep = new File(engineRoot(context), "data-keep");
		boolean kept = false;
		if (dataRoot.isDirectory()) {
			deleteRecursively(keep);
			kept = dataRoot.renameTo(keep);
		}
		deleteRecursively(rootfsDir(context));
		deleteRecursively(new File(engineRoot(context), MANIFEST_FILE));
		restoreKeptData(context, kept);
		EngineState.resetRuntime();
	}

	/** 安装提交后把 data-keep 挪回新 rootfs；rootfs 尚不存在时留给 install 收尾。 */
	public static void restoreKeptData(Context context, boolean kept) {
		File keep = new File(engineRoot(context), "data-keep");
		if (!kept && !keep.isDirectory()) return;
		File restore = new File(rootfsDir(context), "root/piwebui-data");
		if (!restore.getParentFile().isDirectory() && !restore.getParentFile().mkdirs()) {
			EngineState.systemLog("警告：用户数据恢复失败（无法建目录），保留在 " + keep);
			return;
		}
		if (!keep.renameTo(restore)) {
			EngineState.systemLog("警告：用户数据恢复失败，保留在 " + keep);
		}
	}

	/** Prepares the on-rootfs data directories（/root/piwebui-data）；bind 点上的 rename 是 ENOSYS，必须住 rootfs 内部。 */
	public static void ensureDataLayout(Context context) {
		File dataRoot = new File(rootfsDir(context), "root/piwebui-data");
		File[] layout = { new File(dataRoot, "data"), new File(dataRoot, "workspace"), new File(dataRoot, "pi-agent") };
		for (File dir : layout) {
			if (!dir.isDirectory() && !dir.mkdirs()) {
				EngineState.systemLog("警告：无法创建数据目录 " + dir);
			}
		}
	}

	static boolean isInstalledVersionUsable(Context context) {
		Manifest installed = null;
		try {
			installed = readInstalledManifest(context);
		} catch (IOException ignored) {
			return false;
		}
		if (installed == null) return false;
		File node = new File(rootfsDir(context), "usr/local/bin/node");
		return node.isFile() && installed.version.equals(EngineState.snapshot().builtinVersion);
	}
}
