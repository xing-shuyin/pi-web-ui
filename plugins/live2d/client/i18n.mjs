/** 当前界面语言（词典里存在的那一个）；解析与回退由 SDK 统一实现。 */
export function detectLang() {
	return createPluginI18n(DICT).locale;
}

/** 取文案函数：显式 lang 优先（插件设置可选），否则跟随界面语言。 */
export function makeT(lang = "zh") {
	return createPluginI18n(DICT, { locale: lang }).t;
}
