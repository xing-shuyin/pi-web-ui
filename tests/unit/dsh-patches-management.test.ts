import { describe, expect, it, beforeEach, afterEach } from "vitest";
import { mkdtempSync, rmSync, existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { loadDshMarketData } from "../../server/dsh/dsh-market-service.js";

describe("DSH 用户补丁管理核心逻辑", () => {
	let testDir: string;
	let patchDir: string;

	beforeEach(() => {
		testDir = mkdtempSync(join(tmpdir(), "pi-dsh-patch-test-"));
		patchDir = join(testDir, "dsh-patches");
	});

	afterEach(() => {
		try {
			rmSync(testDir, { recursive: true, force: true });
		} catch {}
	});

	it("推导合法 id 并生成标准的 insert patch YAML", () => {
		const spec = "E:\\repo\\dsh-our-free-model";
		const normalizedSpec = spec.replace(/\\/g, "/");
		const escapedName = normalizedSpec.replace(/'/g, "''");

		const base = "dsh-our-free-model";
		const id = base.replace(/^dsh-plugin-|^dsh-/, "").replace(/[^a-zA-Z0-9_-]+/g, "-");

		expect(id).toBe("our-free-model");

		const yamlContent = `# DSH user patch generated by pi-web-ui\n- insert:\n    - id: ${id}\n      name: '${escapedName}'\n      config: {}\n`;
		expect(yamlContent).toContain("id: our-free-model");
		expect(yamlContent).toContain("name: 'E:/repo/dsh-our-free-model'");
	});

	it("安装补丁并覆写旧 disabled 文件", () => {
		const { mkdirSync, writeFileSync } = require("node:fs");
		mkdirSync(patchDir, { recursive: true });

		const id = "my-plugin";
		const disabledFile = join(patchDir, `${id}.yml.disabled`);
		const targetFile = join(patchDir, `${id}.yml`);

		writeFileSync(disabledFile, "old-content", "utf8");
		expect(existsSync(disabledFile)).toBe(true);

		if (existsSync(disabledFile)) {
			rmSync(disabledFile, { force: true });
		}
		writeFileSync(targetFile, "- insert:\n    - id: my-plugin\n", "utf8");

		expect(existsSync(disabledFile)).toBe(false);
		expect(existsSync(targetFile)).toBe(true);
		expect(readFileSync(targetFile, "utf8")).toContain("my-plugin");
	});

	it("启停切换：追加或去除 .disabled 后缀", () => {
		const { mkdirSync, writeFileSync, renameSync } = require("node:fs");
		mkdirSync(patchDir, { recursive: true });

		const activeFile = join(patchDir, "plugin.yml");
		const disabledFile = join(patchDir, "plugin.yml.disabled");

		writeFileSync(activeFile, "content", "utf8");
		expect(existsSync(activeFile)).toBe(true);

		renameSync(activeFile, disabledFile);
		expect(existsSync(activeFile)).toBe(false);
		expect(existsSync(disabledFile)).toBe(true);

		renameSync(disabledFile, activeFile);
		expect(existsSync(activeFile)).toBe(true);
		expect(existsSync(disabledFile)).toBe(false);
	});

	it("扫描与识别 disabled 标志", () => {
		const { mkdirSync, writeFileSync } = require("node:fs");
		mkdirSync(patchDir, { recursive: true });

		writeFileSync(join(patchDir, "a-active.yml"), "a", "utf8");
		writeFileSync(join(patchDir, "b-disabled.yml.disabled"), "b", "utf8");
		writeFileSync(join(patchDir, "c-ignore.txt"), "c", "utf8");

		const files: { name: string; disabled: boolean }[] = [];
		for (const name of readdirSync(patchDir)) {
			if (name.startsWith(".")) continue;
			const isYaml = /\.ya?ml$/iu.test(name);
			const isDisabledYaml = /\.ya?ml\.disabled$/iu.test(name);
			if (!isYaml && !isDisabledYaml) continue;
			files.push({ name, disabled: isDisabledYaml });
		}

		files.sort((a, b) => a.name.localeCompare(b.name));
		expect(files).toHaveLength(2);
		expect(files[0]).toEqual({ name: "a-active.yml", disabled: false });
		expect(files[1]).toEqual({ name: "b-disabled.yml.disabled", disabled: true });
	});

	it("DSH 插件市场：命中有效本地缓存时无需请求远端", async () => {
		const cacheFile = join(testDir, "dsh-market-cache.json");
		const mockData = {
			count: 1,
			updated: "2026-10-13",
			savedAt: Date.now(),
			categories: { model: { en: "Models", zh: "模型" } },
			plugins: [
				{
					name: "dsh-our-free-model",
					owner: "Ebony-Vinyl",
					category: "model",
					version: "2.1.0",
					stars: 100,
					downloads: 500,
				},
			],
		};
		writeFileSync(cacheFile, JSON.stringify(mockData), "utf8");

		const res = await loadDshMarketData(testDir, false);
		expect(res.count).toBe(1);
		expect(res.plugins[0].name).toBe("dsh-our-free-model");
		expect(res.categories.model.zh).toBe("模型");
	});
});
